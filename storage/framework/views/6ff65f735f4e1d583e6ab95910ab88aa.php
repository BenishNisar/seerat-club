        <div class="ac-container">

            <div class="c1-story-grid">


                <article class="ac-prose c1-story-copy">

                    <span class="ac-eyebrow">
                        THE SESSION
                    </span>

                    <h2>
                        Planning, Tawakkul and the journey to Madinah.
                    </h2>

                    <p class="c1-lead">
                        Cycle 1 · Session 11
                    </p>


                    <p>
                        The 11th Seerat Club session was held on
                        4th October 2025 at Shafqat Masjid and focused
                        on the historic and deeply meaningful event of
                        Hijrat to Medina.
                    </p>


                    <p>
                        The session began with Maulana Owais engaging
                        the children in a short interactive quiz about
                        the Islamic calendar. Through this discussion,
                        they discovered that the Islamic calendar begins
                        with the event of Hijrah, a major turning point
                        in Islamic history.
                    </p>


                    <h3>
                        The Journey from Makkah
                    </h3>


                    <p>
                        Children revisited the challenges faced by
                        Prophet Muhammad ﷺ in Makkah during the early
                        years of preaching Islam.
                    </p>


                    <p>
                        As the hardships increased, the Quraysh plotted
                        to kill him. Allah informed the Prophet ﷺ of
                        their plan and commanded him to migrate to Medina.
                    </p>


                    <p>
                        The Prophet ﷺ carefully planned his journey.
                        He selected a trustworthy companion, chose a
                        less travelled route and arranged for a reliable
                        guide.
                    </p>


                    <p>
                        Children learned that careful preparation does
                        not conflict with Tawakkul. The Prophet ﷺ
                        demonstrated how a believer plans responsibly
                        while placing complete trust in Allah.
                    </p>


                    <h3>
                        Seerah Lessons in Everyday Life
                    </h3>


                    <p>
                        These lessons were connected with challenges
                        children experience in daily life, including
                        exam stress, preparing for an important cricket
                        match and making small sacrifices such as pausing
                        playtime for Maghrib prayer.
                    </p>


                    <p>
                        The discussion helped children understand how
                        lessons from the Seerah can guide their decisions,
                        priorities and responses to everyday difficulties.
                    </p>


                    <p>
                        The storytelling portion concluded with the
                        recitation of
                        <strong>Tala‘al Badru ‘Alayna</strong>,
                        helping children imagine the joy with which
                        the people of Medina welcomed Prophet Muhammad ﷺ.
                    </p>


                    <h3>
                        Pakistan as a Blessing and Amanah
                    </h3>


                    <p>
                        In the second half of the session, the focus
                        shifted toward connecting the lessons of Hijrah
                        with Pakistan.
                    </p>


                    <p>
                        Children reflected on how Medina became a place
                        of safety and opportunity for the early Muslims.
                        Pakistan was similarly discussed as a ni‘mah,
                        a blessing, and an Amanah that requires
                        responsibility and care.
                    </p>


                    <h3>
                        Climate Responsibility
                    </h3>


                    <p>
                        The discussion then moved toward one of Pakistan's
                        significant contemporary challenges, climate change.
                    </p>


                    <p>
                        Through the story
                        <strong>Driver Sahib aur Dariya Sutlej</strong>,
                        children explored how flooding and environmental
                        changes affect communities.
                    </p>


                    <p>
                        This was followed by
                        <strong>The Frozen Giants of Karakoram</strong>,
                        presented in collaboration with TDF MagnifiScience.
                    </p>


                    <p>
                        Children learned how melting glaciers in northern
                        Pakistan can contribute to rising river levels
                        and flooding downstream.
                    </p>


                    <p>
                        Local climate heroes were also highlighted,
                        showing children that meaningful environmental
                        action can begin within their own communities.
                    </p>


                    <p>
                        Children were encouraged to adopt practical
                        habits such as reducing plastic use and becoming
                        more thoughtful about their impact on the
                        environment.
                    </p>


                    <h3>
                        Design for a Greener Pakistan
                    </h3>


                    <p>
                        The event concluded with a tote bag painting
                        activity titled
                        <strong>Design for a Greener Pakistan</strong>,
                        led by artist Muneeb Ghouri.
                    </p>


                    <p>
                        The creative activity gave children an enjoyable
                        way to express what they had learned about
                        responsibility, environmental awareness and
                        caring for their homeland.
                    </p>

                </article>



