                        The discussion highlighted the importance of caring
                        for orphans in Islam. Children were encouraged to
                        participate in Sadaqah during Ramadan, and ghullaks
                        were distributed to support the fundraising initiative.
                    </p>


                    <p>
                        The gathering concluded with children writing heartfelt
                        appreciation letters to their parents, bringing the
                        session back to its central themes of gratitude,
                        compassion and care.
