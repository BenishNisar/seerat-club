                    <h2>
                        Tawakkul · Patience · Promises
                    </h2>


                    <p class="ev-story-lead">
                        The sixth Seerat Club session of Cycle 2 brought
                        children together for an engaging evening of stories,
                        reflection, quizzes and practical learning centered
                        around one powerful lesson: Tawakkul.
                    </p>


                    <h3>
                        Trusting Allah when plans change
                    </h3>


                    <p>
                        The session began with the story of Ali, whose
                        football team had reached the tournament final
                        after months of hard work.
                    </p>


                    <p>
                        Just before the important match, Ali became sick
                        and was heartbroken that he would not be able to play.
                    </p>


                    <p>
                        As events unfolded, he discovered that his illness
                        had protected him from a serious injury that occurred
                        during the match. At the same time, being at home
                        gave him an unexpected opportunity to spend meaningful
                        time with his visiting cousin.
                    </p>


                    <p>
                        Through Ali's experience, children reflected on
                        the reality that we may not always understand
                        Allah's plan immediately.
                    </p>


                    <p>
                        Allah is
                        <strong>Al 'Aleem</strong>, The All Knowing,
                        and <strong>Al Hakeem</strong>, The All Wise.
                        What appears disappointing today may contain a
                        benefit that becomes clear later.
                    </p>


                    <h3>
                        The Treaty of Hudaybiah
                    </h3>


                    <p>
                        The discussion then moved to the events leading
                        to the Treaty of Hudaybiah.
                    </p>


                    <p>
                        Prophet Muhammad ﷺ and his companions travelled
                        with the intention of performing Umrah but were
                        stopped outside Makkah.
                    </p>


                    <p>
                        The agreement that followed initially appeared
                        difficult and unfavorable to many of the Muslims.
                    </p>


                    <p>
                        Yet Prophet Muhammad ﷺ demonstrated remarkable
                        patience, placed his trust in Allah and remained
                        committed to honoring the agreement.
                    </p>


                    <p>
                        Children learned that keeping promises is important
                        even when doing so feels difficult or when the
                        immediate outcome does not appear to be in our favor.
                    </p>


                    <p>
                        What initially seemed like a setback eventually
                        became one of the most significant developments
                        in the spread of Islam.
                    </p>


                    <p>
                        This reminded children that success does not always
                        appear immediately. Sometimes patience, wisdom and
                        Tawakkul are required before the benefit becomes clear.
                    </p>


                    <h3>
                        Learning through reflection
                    </h3>


                    <p>
                        An interactive quiz followed the storytelling
                        session, giving children the opportunity to revisit
                        the key events and reflect on how Tawakkul,
                        patience and commitment to promises appeared
                        throughout the story.
                    </p>


                    <h3>
                        RoboWhiz STEM Challenge
                    </h3>


                    <p>
                        The evening concluded with a practical STEM session
                        conducted by <strong>RoboWhiz</strong>.
                    </p>


                    <p>
                        Children built simple series and parallel electrical
                        circuits using batteries, wires, LEDs and resistors.
                    </p>


                    <p>
                        They discovered that every component has an important
                        role to play in allowing a circuit to function
                        successfully.
                    </p>


                    <p>
                        This became a memorable analogy for the lessons
                        of Hudaybiah. Patience, Tawakkul and keeping promises
                        were presented as essential components that worked
                        together and ultimately contributed to the spread
                        of Islam.
                    </p>


                    <p>
                        The session reinforced the idea that Seerah is
                        not simply history. It is a guide for life that
                        teaches children how to build strong character,
                        think wisely and trust Allah through every challenge.
                    </p>

                </article>



